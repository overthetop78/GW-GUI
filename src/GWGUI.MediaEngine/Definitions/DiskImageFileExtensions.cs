namespace GWGUI.MediaEngine.Definitions;

/// <summary>
/// Fournit les extensions de fichiers d’images disque reconnues, lues ou produites par <c>GWGUI.MediaEngine</c>.
/// </summary>
public static class DiskImageFileExtensions
{
    /// <summary>Extension des conteneurs Apple 2IMG.</summary>
    public const string TwoMg = ".2mg";

    /// <summary>Extension des conteneurs de pistes 86F.</summary>
    public const string I86f = ".86f";

    /// <summary>Extension des images ADF Acorn ou Amiga.</summary>
    public const string Adf = ".adf";

    /// <summary>Extension des images Atari ATR.</summary>
    public const string Atr = ".atr";

    /// <summary>Extension générique de certaines images binaires brutes.</summary>
    public const string Bin = ".bin";

    /// <summary>Extension des conteneurs SNATCH-IT CP2.</summary>
    public const string Cp2 = ".cp2";

    /// <summary>Extension des images Apple II DOS 3.2 à treize secteurs par piste.</summary>
    public const string D13 = ".d13";

    /// <summary>Extension des images Commodore 1541 D64.</summary>
    public const string D64 = ".d64";

    /// <summary>Extension des images Commodore 1571 D71.</summary>
    public const string D71 = ".d71";

    /// <summary>Extension des images Commodore 1581 D81.</summary>
    public const string D81 = ".d81";

    /// <summary>Extension explicite des conteneurs Apple DiskCopy 4.2.</summary>
    public const string Dc42 = ".dc42";

    /// <summary>Extension des images sectorielles Apple II en ordre DOS.</summary>
    public const string Do = ".do";

    /// <summary>Extension des images BBC DFS double face.</summary>
    public const string Dsd = ".dsd";

    /// <summary>Extension générique DSK partagée par plusieurs formats d’images disque.</summary>
    public const string Dsk = ".dsk";

    /// <summary>Extension des conteneurs CPCEMU DSK étendus.</summary>
    public const string Edsk = ".edsk";

    /// <summary>Extension IMA des images sectorielles compatibles IBM.</summary>
    public const string Ima = ".ima";

    /// <summary>Extension historique des conteneurs Apple DiskCopy.</summary>
    public const string Image = ".image";

    /// <summary>Extension des conteneurs Dave Dunfield ImageDisk.</summary>
    public const string Imd = ".imd";

    /// <summary>Extension des images de pistes HxC Floppy Emulator.</summary>
    public const string Hfe = ".hfe";

    /// <summary>Extension générique IMG partagée par plusieurs formats d’images disque.</summary>
    public const string Img = ".img";

    /// <summary>Extension des conteneurs Atari ST MSA.</summary>
    public const string Msa = ".msa";

    /// <summary>Extension des images de pistes nibblisées Apple II.</summary>
    public const string Nib = ".nib";

    /// <summary>Extension des images sectorielles Apple II en ordre ProDOS.</summary>
    public const string Po = ".po";

    /// <summary>Extension des captures de flux SuperCard Pro.</summary>
    public const string Scp = ".scp";

    /// <summary>Extension des images BBC DFS simple face.</summary>
    public const string Ssd = ".ssd";

    /// <summary>Extension des images sectorielles Atari ST.</summary>
    public const string St = ".st";

    /// <summary>Extension des conteneurs Sydex TeleDisk.</summary>
    public const string Td0 = ".td0";

    /// <summary>Extension des conteneurs Apple WOZ.</summary>
    public const string Woz = ".woz";
}
